export type GateErrorCode =
  (typeof GATE_ERROR_CODES)[keyof typeof GATE_ERROR_CODES];

export class GateError extends Error {
  readonly code: GateErrorCode;

  constructor(code: GateErrorCode, message: string) {
    super(message);
    this.name = 'GateError';
    this.code = code;
  }
}
