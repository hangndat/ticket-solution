#!/usr/bin/env bash
# Idempotent local FE UAT stack (D9 demo DB + API :3001 + web :3000).
# Fixture only — never deploy production.
#
#   ./scripts/fe-uat-stack.sh bootstrap   # drop/create ticket_d9_demo, migrate, seed
#   ./scripts/fe-uat-stack.sh print-env   # export lines for API + web shells
#   ./scripts/fe-uat-stack.sh check-api   # curl/API sanity (API must listen :3001)
#   ./scripts/fe-uat-stack.sh check-ui    # Playwright markers (API + web up)
#   ./scripts/fe-uat-stack.sh check       # bootstrap + check-api (no UI)
#
# Infra: compose Postgres @127.0.0.1:55432 + Keycloak @127.0.0.1:8080 healthy.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
STATE_DIR="${FE_UAT_STATE_DIR:-${ROOT}/.fe-uat-stack}"
STATE_FILE="${STATE_DIR}/env.sh"
LIB="${ROOT}/scripts/lib"

die() { echo "fe-uat-stack: $*" >&2; exit 1; }

need_cmd() {
  command -v "$1" >/dev/null 2>&1 || die "missing command: $1"
}

wait_keycloak() {
  local tries="${1:-60}"
  for _ in $(seq 1 "$tries"); do
    if curl -sf "http://127.0.0.1:${KEYCLOAK_PORT:-8080}/realms/ticket/.well-known/openid-configuration" >/dev/null; then
      return 0
    fi
    sleep 1
  done
  die "Keycloak not ready on :${KEYCLOAK_PORT:-8080}"
}

wait_postgres() {
  need_cmd pg_isready
  pg_isready -h 127.0.0.1 -p "${POSTGRES_PORT:-55432}" >/dev/null 2>&1 ||
    die "Postgres not ready on :${POSTGRES_PORT:-55432}"
}

write_state() {
  mkdir -p "${STATE_DIR}"
  cat >"${STATE_FILE}" <<EOF
# Generated by fe-uat-stack.sh — local fixture only. Do not commit.
export FE_UAT_ISSUER='${OIDC_ISSUER}'
export FE_UAT_ADMIN_DATABASE_URL='${ADMIN_URL}'
export FE_UAT_RUNTIME_DATABASE_URL='${RUNTIME_URL}'
export CODE_HMAC_PEPPER='${CODE_HMAC_PEPPER}'
export CODE_HMAC_VERSION='${CODE_HMAC_VERSION:-1}'
export TICKET_CREDENTIAL_KEY='${TICKET_CREDENTIAL_KEY}'
export D9_DEMO_STAFF_SUBJECT='${STAFF_SUB}'
export D9_DEMO_ATTENDEE_SUBJECT='${ATTENDEE_SUB}'
export SINGLE_CODE_RESOLVE_GLOBAL='${SINGLE_CODE_RESOLVE_GLOBAL:-1}'
export NEXT_PUBLIC_SINGLE_CODE_RESOLVE='${NEXT_PUBLIC_SINGLE_CODE_RESOLVE:-1}'
EOF
  chmod 600 "${STATE_FILE}"
}

load_state() {
  [[ -f "${STATE_FILE}" ]] || die "no state — run: ./scripts/fe-uat-stack.sh bootstrap"
  # shellcheck source=/dev/null
  source "${STATE_FILE}"
}

cmd_bootstrap() {
  need_cmd node
  need_cmd pnpm
  need_cmd psql
  need_cmd curl
  wait_postgres
  wait_keycloak

  : "${CODE_HMAC_PEPPER:=local-dev-code-pepper-change-me}"
  : "${CODE_HMAC_VERSION:=1}"
  : "${TICKET_CREDENTIAL_KEY:=local-dev-credential-key}"
  : "${SINGLE_CODE_RESOLVE_GLOBAL:=1}"
  : "${NEXT_PUBLIC_SINGLE_CODE_RESOLVE:=1}"

  local tokens_json
  tokens_json="$(node "${LIB}/fe-uat-keycloak-tokens.mjs")"
  OIDC_ISSUER="$(node -e "const j=JSON.parse(process.argv[1]);console.log(j.issuer)" "${tokens_json}")"
  STAFF_SUB="$(node -e "const j=JSON.parse(process.argv[1]);console.log(j.staff.sub)" "${tokens_json}")"
  ATTENDEE_SUB="$(node -e "const j=JSON.parse(process.argv[1]);console.log(j.attendee.sub)" "${tokens_json}")"

  echo "fe-uat-stack: bootstrap DB ticket_d9_demo (migrations + d9_demo_rt + platform grant)"
  local boot_json
  boot_json="$(node "${LIB}/d9-demo-bootstrap-db.mjs")"
  ADMIN_URL="$(node -e "const j=JSON.parse(process.argv[1]);console.log(j.adminUrl)" "${boot_json}")"
  RUNTIME_URL="$(node -e "const j=JSON.parse(process.argv[1]);console.log(j.runtimeUrl)" "${boot_json}")"

  echo "fe-uat-stack: seed D9 (Keycloak subjects + marketing terms-v1)"
  (
    cd "${ROOT}"
    export DATABASE_URL="${ADMIN_URL}"
    export OIDC_ISSUER="${OIDC_ISSUER}"
    export CODE_HMAC_PEPPER CODE_HMAC_VERSION
    export D9_DEMO_STAFF_SUBJECT="${STAFF_SUB}"
    export D9_DEMO_ATTENDEE_SUBJECT="${ATTENDEE_SUB}"
    ./scripts/d9-demo-seed.sh
  )

  write_state
  echo "fe-uat-stack: bootstrap OK — state ${STATE_FILE}"
}

cmd_print_env() {
  load_state
  cat <<EOF
# API (listen :3001)
export DATABASE_URL='${FE_UAT_RUNTIME_DATABASE_URL}'
export HOST=127.0.0.1 PORT=3001 NODE_ENV=development
export OIDC_PROVIDER=keycloak OIDC_ISSUER='${FE_UAT_ISSUER}'
export OIDC_AUDIENCE=ticket-api OIDC_JWKS_URL='${FE_UAT_ISSUER}/protocol/openid-connect/certs'
export CODE_HMAC_PEPPER='${CODE_HMAC_PEPPER}' CODE_HMAC_VERSION='${CODE_HMAC_VERSION}'
export TICKET_CREDENTIAL_KEY='${TICKET_CREDENTIAL_KEY}'
export EMAIL_ALLOW_NOOP=1
export SINGLE_CODE_RESOLVE_GLOBAL='${SINGLE_CODE_RESOLVE_GLOBAL}'

# Web (next dev :3000) — copy apps/web/.env.example then override:
export API_BASE_URL=http://127.0.0.1:3001
export OIDC_ISSUER='${FE_UAT_ISSUER}'
export WEB_PUBLIC_ORIGIN=http://localhost:3000 PRODUCT_ORIGIN=http://localhost:3000
export NEXT_PUBLIC_SINGLE_CODE_RESOLVE='${NEXT_PUBLIC_SINGLE_CODE_RESOLVE}'
EOF
}

cmd_check_api() {
  load_state
  export OIDC_ISSUER="${FE_UAT_ISSUER}"
  export CODE_HMAC_PEPPER TICKET_CREDENTIAL_KEY
  node "${LIB}/fe-uat-stack-sanity.mjs"
}

cmd_check_ui() {
  load_state
  export OIDC_ISSUER="${FE_UAT_ISSUER}"
  export CODE_HMAC_PEPPER TICKET_CREDENTIAL_KEY
  export FE_UAT_API_URL="${FE_UAT_API_URL:-http://127.0.0.1:3001}"
  export FE_UAT_WEB_URL="${FE_UAT_WEB_URL:-http://localhost:3000}"
  node "${LIB}/fe-uat-stack-sanity.mjs" --ui
}

usage() {
  cat <<'USAGE'
fe-uat-stack — D9 demo stack for FE UAT (Epic #715)

Commands:
  bootstrap    Drop/create ticket_d9_demo, migrate, seed with live Keycloak subs
  print-env    Print export block for API + web terminals
  check-api    API sanity (health, public terms, staff caps, redeem, tickets)
  check-ui     API + Playwright testids (needs API :3001 + web :3000)
  check        bootstrap then check-api

Env overrides:
  CODE_HMAC_PEPPER, TICKET_CREDENTIAL_KEY (must match seed + API)
  SINGLE_CODE_RESOLVE_GLOBAL=1, NEXT_PUBLIC_SINGLE_CODE_RESOLVE=1 (default on)
  FE_UAT_STATE_DIR — where env.sh is written (default: .fe-uat-stack/)
USAGE
}

main() {
  local cmd="${1:-}"
  case "${cmd}" in
    bootstrap) cmd_bootstrap ;;
    print-env) cmd_print_env ;;
    check-api) cmd_check_api ;;
    check-ui) cmd_check_ui ;;
    check)
      cmd_bootstrap
      cmd_check_api
      ;;
    -h|--help|help|"") usage ;;
    *) die "unknown command '${cmd}' (try --help)" ;;
  esac
}

main "$@"
